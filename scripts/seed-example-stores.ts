/**
 * ============================================================================
 *  EXAMPLE STORE SEED
 * ============================================================================
 *
 *  Run with:  npx tsx scripts/seed-example-stores.ts
 *
 *  Adds one fully-worked shop per package - Silver, Gold, Platinum, Super - so
 *  the marketplace demonstrates what each package unlocks rather than describing
 *  it in a table nobody visits.
 *
 *  THE POINT OF THE SPREAD
 *  ----------------------
 *  Silver and Gold are a SINGLE store with a catalogue and no stock control,
 *  because that is what those packages buy. Platinum and Super additionally get
 *  INVENTORY ITEMS and WAREHOUSE NODES, because `inventory` and
 *  `custom_inventory` are Platinum/Super features - seeding them on a Silver shop
 *  would show a capability the package does not grant.
 *
 *  Each store gets a logo, a cover banner, and an image on every product. Those
 *  are real local SVG generated by `generate-media.ts`; nothing here points at a
 *  third-party image host, so a demo can never render a borrowed picture.
 *
 *  IDEMPOTENT. A store that already exists is left exactly as it is, so this can
 *  be re-run safely and never overwrites a merchant's own edits.
 */

import fs from "node:fs";
import path from "node:path";

const dataDir = process.env.YENE_DATA_DIR ?? path.resolve(process.cwd(), "data");

function read<T>(file: string): T[] {
  const full = path.join(dataDir, file);
  if (!fs.existsSync(full)) return [];
  return JSON.parse(fs.readFileSync(full, "utf8")) as T[];
}

function write(file: string, value: unknown): void {
  fs.writeFileSync(path.join(dataDir, file), JSON.stringify(value, null, 2), "utf8");
}

